"""Kerberos client setup: krb5.conf, a keytab built from the bind password, and kinit.

The password is read from a mounted secret file and only ever travels on ktutil's stdin. The keytab and
credential cache live in ADSYNC_RUNTIME_DIR (mount a memory-backed emptyDir there), mode 0700.
"""

from __future__ import annotations

import hashlib
import os
import subprocess
from urllib.parse import urlsplit

from .config import Config


class KerberosError(Exception):
    pass


def render_krb5_conf(cfg: Config) -> str:
    enc = " ".join(cfg.enctypes)
    kdcs = "\n".join(f"    kdc = {k}" for k in cfg.kdcs)
    hosts = [urlsplit(u).hostname.lower() for u in cfg.ldap_urls]
    mapping = "\n".join(f"  {h} = {cfg.realm}" for h in dict.fromkeys(hosts + list(cfg.kdcs)))
    return f"""# generated by spoolfree-adsync
[libdefaults]
  default_realm = {cfg.realm}
  dns_lookup_realm = false
  dns_lookup_kdc = false
  # Service principals are ldap/<the FQDN in ADSYNC_LDAP_URLS>, never a reverse-DNS or canonicalized name.
  rdns = false
  dns_canonicalize_hostname = false
  default_tkt_enctypes = {enc}
  default_tgs_enctypes = {enc}
  permitted_enctypes = {enc}
  forwardable = false
  ticket_lifetime = 10h

[realms]
  {cfg.realm} = {{
{kdcs}
  }}

[domain_realm]
{mapping}
"""


def read_secret_file(path: str) -> str:
    try:
        with open(path, encoding="utf-8") as f:
            value = f.read().strip("\r\n")
    except OSError as e:
        raise KerberosError(f"cannot read {path}: {e.strerror}") from None
    if not value:
        raise KerberosError(f"{path} is empty")
    if "\n" in value or "\r" in value:
        raise KerberosError(f"{path} must hold a single line")
    return value


def _redact(text: str, secret: str) -> str:
    text = text.replace(secret, "[redacted]") if secret else text
    return " ".join(text.split())[:500]


class Kerberos:
    def __init__(self, cfg: Config, run=subprocess.run):
        self.cfg = cfg
        self.run = run
        self.dir = cfg.runtime_dir
        self.keytab = os.path.join(self.dir, "client.keytab")
        self.ccache = os.path.join(self.dir, "ccache")
        self._keytab_state: str | None = None
        self.kvno = cfg.kvno or 1

    def prepare(self) -> None:
        os.makedirs(self.dir, mode=0o700, exist_ok=True)
        os.chmod(self.dir, 0o700)
        conf = os.path.join(self.dir, "krb5.conf")
        with open(conf, "w", encoding="utf-8") as f:
            f.write(render_krb5_conf(self.cfg))
        os.environ["KRB5_CONFIG"] = conf
        os.environ["KRB5CCNAME"] = f"FILE:{self.ccache}"
        os.environ.pop("KRB5_CLIENT_KTNAME", None)

    def _env(self) -> dict:
        return {k: v for k, v in os.environ.items() if k in ("PATH", "LANG", "LC_ALL", "KRB5_CONFIG", "KRB5CCNAME", "HOME", "TMPDIR")}

    def ensure_keytab(self, force: bool = False) -> bool:
        """(Re)builds the keytab when the password file or the kvno changed. Returns True if rebuilt."""
        password = read_secret_file(self.cfg.password_file)
        state = hashlib.sha256(f"{self.kvno}\0{password}".encode()).hexdigest()
        if not force and state == self._keytab_state and os.path.exists(self.keytab):
            return False
        self._build_keytab(password)
        self._keytab_state = state
        return True

    def _build_keytab(self, password: str) -> None:
        tmp = self.keytab + ".new"
        if os.path.exists(tmp):
            os.remove(tmp)
        # -f asks the KDC for the salt (AD salts user keys with REALM + sAMAccountName), so nothing is guessed.
        lines = []
        for enc in self.cfg.enctypes:
            lines.append(f"addent -password -p {self.cfg.principal} -k {self.kvno} -e {enc} -f")
            lines.append(password)
        lines += [f"wkt {tmp}", "quit"]
        old = os.umask(0o077)
        try:
            r = self.run(["ktutil"], input="\n".join(lines) + "\n", capture_output=True, text=True, env=self._env(), timeout=60)
        finally:
            os.umask(old)
        out = _redact((r.stderr or "").strip() or (r.stdout or ""), password)
        if r.returncode != 0 or not os.path.exists(tmp) or os.path.getsize(tmp) == 0:
            raise KerberosError(f"ktutil failed: {out}")
        n = self.keytab_entries(tmp)
        if n != len(self.cfg.enctypes):
            os.remove(tmp)
            raise KerberosError(f"ktutil wrote {n} keytab entries, expected {len(self.cfg.enctypes)}: {out}")
        os.replace(tmp, self.keytab)

    def keytab_entries(self, path: str) -> int:
        r = self.run(["klist", "-k", "-t", path], capture_output=True, text=True, env=self._env(), timeout=30)
        if r.returncode != 0:
            return 0
        return sum(1 for line in r.stdout.splitlines() if self.cfg.principal.lower() in line.lower())

    def kinit(self) -> None:
        r = self.run(
            ["kinit", "-k", "-t", self.keytab, self.cfg.principal],
            capture_output=True,
            text=True,
            env=self._env(),
            timeout=60,
        )
        if r.returncode != 0:
            raise KerberosError("kinit failed: " + _redact((r.stderr or "").strip() or (r.stdout or ""), ""))

    def login(self) -> None:
        """Keytab up to date + a fresh TGT. On failure rebuilds the keytab once (password rotated, new kvno)."""
        self.ensure_keytab()
        try:
            self.kinit()
        except KerberosError:
            self.ensure_keytab(force=True)
            self.kinit()

    def set_kvno(self, kvno: int) -> bool:
        """Auto kvno: rebuild the keytab with the account's real kvno (msDS-KeyVersionNumber)."""
        if self.cfg.kvno is not None or kvno == self.kvno or kvno < 1:
            return False
        self.kvno = kvno
        self.ensure_keytab(force=True)
        return True
